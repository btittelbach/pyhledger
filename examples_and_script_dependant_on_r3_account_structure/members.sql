INSTEAD OF UPDATE OF c_contact ON "wiki_active_members_list"
BEGIN
  INSERT INTO "contact"("rowid","p_id","ct_id","c_contact") VALUES (NEW.c_id,NEW.p_id,2,NEW.c_contact);
